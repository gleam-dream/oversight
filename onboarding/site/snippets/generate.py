#!/usr/bin/env python3
"""Write ../src/pages/gleam_lang/snippets.gleam from this package.

Every `// region: name` ... `// endregion` block under src/ becomes a
constant `name` (dashes become underscores), and every captured compiler
output in output/<name>.txt becomes `<name>_error`. The site shows these
constants, so the code it shows is code that compiles.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
TARGET = ROOT.parent / "src" / "pages" / "gleam_lang" / "snippets.gleam"


def literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped.replace("\n", "\\n") + '"'


def regions() -> dict[str, str]:
    found = {}
    for path in sorted((ROOT / "src").rglob("*.gleam")):
        name, lines = None, []
        for line in path.read_text().splitlines():
            start = re.match(r"\s*// region: ([a-z0-9-]+)\s*$", line)
            if start:
                name, lines = start.group(1), []
            elif re.match(r"\s*// endregion\s*$", line) and name:
                if name in found:
                    sys.exit(f"region {name} defined twice")
                found[name] = "\n".join(lines).strip("\n")
                name = None
            elif name:
                lines.append(line)
        if name:
            sys.exit(f"region {name} in {path} has no endregion")
    return found


def outputs() -> dict[str, str]:
    return {
        path.stem + "-error": path.read_text().rstrip()
        for path in sorted((ROOT / "output").glob("*.txt"))
    }


def main() -> None:
    entries = {**regions(), **outputs()}
    body = [
        "//// Generated by snippets/generate.py from the compiled snippets",
        "//// package. Do not edit: change snippets/src or rerun capture.sh.",
        "",
    ]
    for name, text in entries.items():
        body.append(f"pub const {name.replace('-', '_')} = {literal(text)}")
        body.append("")
    TARGET.write_text("\n".join(body).rstrip() + "\n")
    # Written as the formatter would, so regenerating never shows a diff.
    subprocess.run(["gleam", "format", str(TARGET)], check=True)
    print(f"wrote {len(entries)} snippets to {TARGET.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
